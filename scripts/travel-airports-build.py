#!/usr/bin/env python3
"""Builds app/Services/Travel/Data/airports.php from the OurAirports open data (public domain).

    python3 scripts/travel-airports-build.py airports.csv countries.csv > app/Services/Travel/Data/airports.php

Source files: https://github.com/davidmegginson/ourairports-data (airports.csv, countries.csv).
Kept: airports with an IATA code AND scheduled service (large, medium and small). Everything else
(heliports, closed fields, airstrips with no scheduled flights) is left out, because a customer can
only be quoted a flight to somewhere an airline actually flies.
"""
import csv, re, sys, unicodedata, datetime

def key(s):
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode('ascii').lower()
    return re.sub(r'\s+', ' ', re.sub(r'[^a-z0-9 ]+', ' ', s)).strip()

def city_clean(s):
    s = re.sub(r'\(.*?\)', '', s)          # "Dubai(Jebel Ali)" -> "Dubai"
    s = s.split(',')[0]                    # "Birmingham, West Midlands" -> "Birmingham"
    s = s.split('/')[0]
    return s.strip()

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

airports_csv, countries_csv = sys.argv[1], sys.argv[2]
countries = {r['code']: r['name'] for r in csv.DictReader(open(countries_csv, encoding='utf-8'))}
size = {'large_airport': 'L', 'medium_airport': 'M', 'small_airport': 'S'}
rows, seen = [], set()
for r in csv.DictReader(open(airports_csv, encoding='utf-8')):
    code = (r['iata_code'] or '').strip().upper()
    if not re.fullmatch(r'[A-Z]{3}', code) or r['scheduled_service'] != 'yes' or r['type'] not in size or code in seen:
        continue
    city = city_clean(r['municipality'] or '')
    if not city:
        continue
    seen.add(code)
    rows.append((code, r['name'].strip(), city, r['iso_country'], size[r['type']]))
rows.sort()
used = sorted({r[3] for r in rows})

out = ["<?php", "",
       "// GENERATED by scripts/travel-airports-build.py — do not edit by hand.",
       "// Source: OurAirports open data (public domain), https://github.com/davidmegginson/ourairports-data",
       "// Built %s · %d airports with an IATA code and scheduled service." % (datetime.date.today().isoformat(), len(rows)),
       "// Row: [iata, airport name, city, ISO country, size L|M|S]", "",
       "return [", "    'countries' => ["]
out += ["        %s => %s," % (q(c), q(countries.get(c, c))) for c in used]
out += ["    ],", "    'airports' => ["]
out += ["        [%s, %s, %s, %s, %s]," % tuple(q(x) for x in r) for r in rows]
out += ["    ],", "];", ""]
sys.stdout.write("\n".join(out))
